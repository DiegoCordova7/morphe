package dev.morphe.ast.operator;

/**
 * Represents the assignment operators available in the Morphe language.
 *
 * <p>The operators include simple assignment and compound assignments,
 * which combine an arithmetic operation with assignment.</p>
 */
public enum AssignmentOperator {
  ASSIGN,
  ADD,
  SUBTRACT,
  MULTIPLY,
  DIVIDE,
  MODULO
}